create or replace function public.get_marker_submissions_page(
    p_game_id text,
    p_status text default 'pending',
    p_limit integer default 10,
    p_offset integer default 0
)
returns table (
    id bigint,
    game_id text,
    marker_id bigint,
    submission_type text,
    correction_kind text,
    status text,
    submitted_by uuid,
    submitted_username text,
    payload jsonb,
    note text,
    reviewed_by uuid,
    reviewed_username text,
    reviewed_at timestamptz,
    review_note text,
    created_at timestamptz,
    updated_at timestamptz,
    revision_count integer,
    total_count bigint
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
    if not private.can_moderate_deepmap() then
        raise exception 'MODERATOR_REQUIRED' using errcode = 'P0001';
    end if;
    if p_status not in ('pending','approved','rejected') then
        raise exception 'INVALID_STATUS' using errcode = 'P0001';
    end if;

    return query
    select
        s.id,s.game_id,s.marker_id,s.submission_type,s.correction_kind,s.status,s.submitted_by,
        submitter.username,s.payload,s.note,s.reviewed_by,reviewer.username,s.reviewed_at,s.review_note,s.created_at,s.updated_at,
        (select count(*)::integer from private.marker_submission_revisions r where r.submission_id=s.id),
        count(*) over()
    from public.marker_submissions s
    left join public.profiles submitter on submitter.id=s.submitted_by
    left join public.profiles reviewer on reviewer.id=s.reviewed_by
    where (p_game_id is null or p_game_id='' or s.game_id=p_game_id)
      and s.status=p_status
    order by case when p_status='pending' then s.updated_at else coalesce(s.reviewed_at,s.updated_at) end desc, s.id desc
    limit greatest(1,least(coalesce(p_limit,10),100))
    offset greatest(coalesce(p_offset,0),0);
end;
$$;

revoke all on function public.get_marker_submissions_page(text, text, integer, integer) from public, anon, authenticated;
grant execute on function public.get_marker_submissions_page(text, text, integer, integer) to authenticated;

-- Block suspended users from contribution writes/reads while keeping staff access.
drop policy if exists "marker_submissions_read_own_or_staff" on public.marker_submissions;
create policy "marker_submissions_read_own_or_staff"
on public.marker_submissions
for select
to authenticated
using (
    (submitted_by = (select auth.uid()) and not private.is_deepmap_banned())
    or private.can_moderate_deepmap()
);

drop policy if exists "marker_submissions_insert_own" on public.marker_submissions;
create policy "marker_submissions_insert_own"
on public.marker_submissions
for insert
to authenticated
with check (
    not private.is_deepmap_banned()
    and submitted_by = (select auth.uid())
    and status = 'pending'
    and reviewed_by is null
    and reviewed_at is null
    and review_note is null
);

drop policy if exists "marker_submissions_update_own_pending" on public.marker_submissions;
create policy "marker_submissions_update_own_pending"
on public.marker_submissions
for update
to authenticated
using (
    not private.is_deepmap_banned()
    and submitted_by = (select auth.uid())
    and status = 'pending'
)
with check (
    not private.is_deepmap_banned()
    and submitted_by = (select auth.uid())
    and status = 'pending'
);

-- Current profile editing also respects the app-level suspension.
drop policy if exists "profiles_update_own" on public.profiles;
create policy "profiles_update_own"
on public.profiles
for update
to authenticated
using ((select auth.uid()) = id and not private.is_deepmap_banned())
with check ((select auth.uid()) = id and not private.is_deepmap_banned());

-- =========================================================
-- 5. GLOBAL ADMIN AUDIT LOG
-- =========================================================

drop function if exists public.get_deepmap_admin_audit(integer, integer);
create function public.get_deepmap_admin_audit(
    p_limit integer default 25,
    p_offset integer default 0
)
returns table (
    event_id text,
    action text,
    actor_username text,
    target_username text,
    game_id text,
    submission_id bigint,
    detail text,
    created_at timestamptz,
    total_count bigint
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
    if not private.is_deepmap_admin() then
        raise exception 'ADMIN_REQUIRED' using errcode = 'P0001';
    end if;

    return query
    with events as (
        select
            'role-' || r.id::text as event_id,
            r.action,
            actor.username as actor_username,
            target.username as target_username,
            null::text as game_id,
            null::bigint as submission_id,
            null::text as detail,
            r.created_at
        from private.deepmap_role_audit r
        left join public.profiles actor on actor.id=r.actor_id
        left join public.profiles target on target.id=r.target_user_id

        union all

        select
            'ban-' || b.id::text,
            b.action,
            actor.username,
            target.username,
            null::text,
            null::bigint,
            case
                when b.action='user_banned' then coalesce(b.reason,'') || case when b.expires_at is null then ' · permanent' else ' · until ' || b.expires_at::text end
                else coalesce(b.reason,'')
            end,
            b.created_at
        from private.deepmap_ban_audit b
        left join public.profiles actor on actor.id=b.actor_id
        left join public.profiles target on target.id=b.target_user_id

        union all

        select
            'submission-' || s.id::text || '-' || s.status,
            case when s.status='approved' then 'submission_approved' else 'submission_rejected' end,
            reviewer.username,
            submitter.username,
            s.game_id,
            s.id,
            nullif(s.review_note,''),
            coalesce(s.reviewed_at,s.updated_at)
        from public.marker_submissions s
        left join public.profiles reviewer on reviewer.id=s.reviewed_by
        left join public.profiles submitter on submitter.id=s.submitted_by
        where s.status in ('approved','rejected')
    )
    select
        e.event_id,e.action,e.actor_username,e.target_username,e.game_id,e.submission_id,e.detail,e.created_at,
        count(*) over()
    from events e
    order by e.created_at desc
    limit greatest(1,least(coalesce(p_limit,25),100))
    offset greatest(coalesce(p_offset,0),0);
end;
$$;

revoke all on function public.get_deepmap_admin_audit(integer, integer) from public, anon, authenticated;
grant execute on function public.get_deepmap_admin_audit(integer, integer) to authenticated;

commit;
