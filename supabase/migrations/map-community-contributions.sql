-- DeepMap — Community marker contributions + moderation
-- Users can submit new markers and corrections without direct write access to public.marcadores.
-- Admins/moderators review submissions; accepted changes are applied server-side.

begin;

create schema if not exists private;

-- =========================================================
-- 1. MARKER SUBMISSIONS
-- =========================================================

create table if not exists public.marker_submissions (
    id bigint generated by default as identity primary key,

    game_id text not null,
    marker_id bigint references public.marcadores(id) on delete cascade,

    submission_type text not null
        check (submission_type in ('create', 'correction')),

    correction_kind text
        check (
            correction_kind is null
            or correction_kind in ('text', 'location', 'image', 'other')
        ),

    status text not null default 'pending'
        check (status in ('pending', 'approved', 'rejected', 'cancelled')),

    -- UUID kept even if the account is later deleted; public profile resolution can then fall back to an anonymised author.
    submitted_by uuid not null,

    payload jsonb not null default '{}'::jsonb,
    note text,

    reviewed_by uuid,
    reviewed_at timestamptz,
    review_note text,

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint marker_submissions_target_required
        check (
            submission_type <> 'correction'
            or marker_id is not null
        )
);

create index if not exists marker_submissions_game_status_idx
    on public.marker_submissions (game_id, status, created_at desc);

create index if not exists marker_submissions_user_status_idx
    on public.marker_submissions (submitted_by, status, created_at desc);

create index if not exists marker_submissions_marker_idx
    on public.marker_submissions (marker_id, created_at desc)
    where marker_id is not null;

-- =========================================================
-- 2. INTERNAL REVISION HISTORY
-- =========================================================

create table if not exists private.marker_submission_revisions (
    id bigint generated by default as identity primary key,
    submission_id bigint not null
        references public.marker_submissions(id)
        on delete cascade,
    revision_no integer not null,
    edited_by uuid,
    payload jsonb not null default '{}'::jsonb,
    note text,
    created_at timestamptz not null default now(),
    unique (submission_id, revision_no)
);

alter table private.marker_submission_revisions enable row level security;
revoke all on table private.marker_submission_revisions
from public, anon, authenticated;

create or replace function private.deepmap_capture_submission_revision()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_revision integer;
begin
    if tg_op = 'UPDATE'
       and new.payload is not distinct from old.payload
       and new.note is not distinct from old.note
       and new.correction_kind is not distinct from old.correction_kind then
        return new;
    end if;

    select coalesce(max(r.revision_no), 0) + 1
      into v_revision
      from private.marker_submission_revisions as r
     where r.submission_id = new.id;

    insert into private.marker_submission_revisions (
        submission_id,
        revision_no,
        edited_by,
        payload,
        note
    ) values (
        new.id,
        v_revision,
        (select auth.uid()),
        new.payload,
        new.note
    );

    return new;
end;
$$;

revoke all on function private.deepmap_capture_submission_revision()
from public, anon, authenticated;

drop trigger if exists deepmap_marker_submission_revision
on public.marker_submissions;

create trigger deepmap_marker_submission_revision
after insert or update of payload, note, correction_kind
on public.marker_submissions
for each row
execute function private.deepmap_capture_submission_revision();

