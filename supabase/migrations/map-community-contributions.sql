create function public.get_public_marker_attribution(p_game_id text)
returns table (
    marker_id bigint,
    published_username text,
    modified_username text,
    approved_username text
)
language sql
stable
security definer
set search_path = ''
as $$
    select
        a.marker_id,
        creator.username as published_username,
        case
            when a.updated_by is not null
             and a.updated_at is not null
             and (a.created_at is null or a.updated_at > a.created_at)
            then modifier.username
            else null
        end as modified_username,
        approver.username as approved_username
    from private.marker_editor_audit as a
    join public.marcadores as m
      on m.id = a.marker_id
    left join public.profiles as creator
      on creator.id = a.created_by
    left join public.profiles as modifier
      on modifier.id = a.updated_by
    left join public.profiles as approver
      on approver.id = a.approved_by
    where m.game_id = p_game_id
      and m.is_published = true;
$$;

