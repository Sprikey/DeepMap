-- DeepMap — moderator roles, admin user management and moderator review access
-- Run after the previous Editor 2.0/community moderation migrations.

begin;

create schema if not exists private;

-- =========================================================
-- 1. MODERATOR ROLE + ROLE AUDIT
-- =========================================================

create table if not exists private.deepmap_moderators (
    user_id uuid primary key
        references auth.users(id)
        on delete cascade,
    created_by uuid,
    created_at timestamptz not null default now()
);

create table if not exists private.deepmap_role_audit (
    id bigint generated by default as identity primary key,
    actor_id uuid,
    target_user_id uuid not null,
    action text not null check (action in ('moderator_granted', 'moderator_revoked')),
    created_at timestamptz not null default now()
);

alter table private.deepmap_moderators enable row level security;
alter table private.deepmap_role_audit enable row level security;
revoke all on table private.deepmap_moderators from public, anon, authenticated;
revoke all on table private.deepmap_role_audit from public, anon, authenticated;

create or replace function private.is_deepmap_moderator()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
          from private.deepmap_moderators as m
         where m.user_id = (select auth.uid())
    );
$$;

create or replace function private.can_moderate_deepmap()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select private.is_deepmap_admin() or private.is_deepmap_moderator();
$$;

revoke all on function private.is_deepmap_moderator() from public, anon, authenticated;
revoke all on function private.can_moderate_deepmap() from public, anon, authenticated;
grant execute on function private.is_deepmap_moderator() to authenticated;
grant execute on function private.can_moderate_deepmap() to authenticated;

create or replace function public.get_deepmap_role()
returns text
language sql
stable
security definer
set search_path = ''
as $$
    select case
        when private.is_deepmap_admin() then 'admin'
        when private.is_deepmap_moderator() then 'moderator'
        else 'user'
    end;
$$;

revoke all on function public.get_deepmap_role() from public, anon, authenticated;
grant execute on function public.get_deepmap_role() to authenticated;

-- =========================================================
-- 2. ADMIN USER DIRECTORY / ROLE MANAGEMENT
-- =========================================================

create or replace function public.get_deepmap_users(
    p_role_filter text default 'all',
    p_search text default null,
    p_limit integer default 20,
    p_offset integer default 0
)
returns table (
    user_id uuid,
    username text,
    display_name text,
    joined_at timestamptz,
    role text,
    contribution_count bigint,
    pending_count bigint,
    approved_count bigint,
    rejected_count bigint,
    total_count bigint
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
    if not private.is_deepmap_admin() then
        raise exception 'ADMIN_REQUIRED' using errcode = 'P0001';
    end if;

    if p_role_filter not in ('all', 'user', 'moderator') then
        raise exception 'INVALID_ROLE_FILTER' using errcode = 'P0001';
    end if;

    return query
    select
        p.id as user_id,
        p.username,
        p.public_display_name as display_name,
        p.joined_at,
        case
            when a.user_id is not null then 'admin'
            when m.user_id is not null then 'moderator'
            else 'user'
        end as role,
        count(s.id)::bigint as contribution_count,
        count(s.id) filter (where s.status = 'pending')::bigint as pending_count,
        count(s.id) filter (where s.status = 'approved')::bigint as approved_count,
        count(s.id) filter (where s.status = 'rejected')::bigint as rejected_count,
        count(*) over() as total_count
    from public.profiles as p
    left join private.deepmap_admins as a on a.user_id = p.id
    left join private.deepmap_moderators as m on m.user_id = p.id
    left join public.marker_submissions as s on s.submitted_by = p.id
    where
        (
            nullif(btrim(coalesce(p_search, '')), '') is null
            or p.username ilike '%' || lower(btrim(p_search)) || '%'
        )
        and (
            p_role_filter = 'all'
            or (p_role_filter = 'user' and a.user_id is null and m.user_id is null)
            or (p_role_filter = 'moderator' and a.user_id is null and m.user_id is not null)
        )
    group by p.id, p.username, p.public_display_name, p.joined_at, a.user_id, m.user_id
    order by
        case when a.user_id is not null then 0 when m.user_id is not null then 1 else 2 end,
        p.username asc
    limit greatest(1, least(coalesce(p_limit, 20), 100))
    offset greatest(coalesce(p_offset, 0), 0);
end;
$$;

revoke all on function public.get_deepmap_users(text, text, integer, integer) from public, anon, authenticated;
grant execute on function public.get_deepmap_users(text, text, integer, integer) to authenticated;

create or replace function public.set_deepmap_moderator(
    p_user_id uuid,
    p_enabled boolean
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_actor uuid := (select auth.uid());
begin
    if not private.is_deepmap_admin() then
        raise exception 'ADMIN_REQUIRED' using errcode = 'P0001';
    end if;

    if p_user_id is null or not exists (select 1 from public.profiles where id = p_user_id) then
        raise exception 'USER_NOT_FOUND' using errcode = 'P0001';
    end if;

    if exists (select 1 from private.deepmap_admins where user_id = p_user_id) then
        raise exception 'ADMIN_ROLE_PROTECTED' using errcode = 'P0001';
    end if;

    if p_enabled then
        insert into private.deepmap_moderators (user_id, created_by)
        values (p_user_id, v_actor)
        on conflict (user_id) do nothing;

        if found then
            insert into private.deepmap_role_audit (actor_id, target_user_id, action)
            values (v_actor, p_user_id, 'moderator_granted');
        end if;
    else
        delete from private.deepmap_moderators where user_id = p_user_id;

        if found then
            insert into private.deepmap_role_audit (actor_id, target_user_id, action)
            values (v_actor, p_user_id, 'moderator_revoked');
        end if;
    end if;
end;
$$;

revoke all on function public.set_deepmap_moderator(uuid, boolean) from public, anon, authenticated;
grant execute on function public.set_deepmap_moderator(uuid, boolean) to authenticated;

